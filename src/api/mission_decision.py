@dataclass(frozen=True)
class MissionOption:
    """What one scenario measured, or why the router refused it."""

    scenario: MissionScenario
    feasible: bool
    refusal_outcome: str | None
    refusal_reason: str | None
    profiles: dict = field(default_factory=dict)
    environment: dict = field(default_factory=dict)

    def objective_values(self) -> dict:
        """Per profile, the attributes Phase 6 asks for. Measured, not judged."""
        out = {}
        for name, p in self.profiles.items():
            if not p.get("success"):
                out[name] = {"routed": False, "outcome": p.get("outcome"),
                             "reason": p.get("reason")}
                continue
            row = {
                "routed": True,
                "distance_km": p.get("distance_km"),
                "travel_time_h": p.get("travel_time_h"),
                "configured_cost": p.get("configured_cost"),
                "polaris_contribution": p.get("polaris_contribution"),
                "environmental_contribution": p.get("environmental_contribution"),
                "iceberg_exposure_contribution":
                    p.get("iceberg_exposure_contribution"),
                "max_iceberg_exposure": p.get("max_iceberg_exposure"),
                "estimated_fuel": p.get("estimated_fuel"),
                "estimated_fuel_units": p.get("estimated_fuel_units"),
                "estimated_fuel_per_km": p.get("estimated_fuel_per_km"),
                "cells": len(p.get("path") or ()),
            }
            if name == PROFILE_SHORTEST:
                row["is_a_fuel_figure"] = False
            out[name] = row
        return out

    def provenance(self) -> dict:
        """PHASE 8: everything needed to say what this option actually was."""
        d = self.scenario.to_dict()
        d.update({
            "feasible": self.feasible,
            "refusal_outcome": self.refusal_outcome,
            "refusal_reason": self.refusal_reason,
            "environment": self.environment,
            "estimated_fuel_provenance": self._fuel_provenance(),
            "iceberg_exposure": self._iceberg_status(),
            "feasibility_is_the_routers_word": True,
            "attributes_that_never_cause_a_refusal":
                list(NOT_FEASIBILITY_CRITERIA),
        })
        return d

    def _fuel_provenance(self) -> dict | None:
        for p in self.profiles.values():
            if p.get("success") and p.get("fuel_provenance"):
                return p["fuel_provenance"]
        return None

    def _iceberg_status(self) -> dict:
        if self.scenario.iceberg_exposure == ICEBERG_OMITTED:
            return {"status": ICEBERG_OMITTED,
                    "reason": self.scenario.iceberg_omission_reason,
                    "reinterpreted_24h_or_48h_rasters": False,
                    "zero_filled": False, "persisted": False,
                    "is_an_operational_assessment": False}
        for p in self.profiles.values():
            if p.get("success") and p.get("iceberg_provenance"):
                return dict(p["iceberg_provenance"], status="priced")
        return {"status": "not_priced",
                "reason": "no profile routed, so nothing was priced"}

    def to_dict(self) -> dict:
        return {"scenario": self.scenario.to_dict(),
                "feasible": self.feasible,
                "refusal_outcome": self.refusal_outcome,
                "refusal_reason": self.refusal_reason,
                "objectives": self.objective_values(),
                "provenance": self.provenance()}


