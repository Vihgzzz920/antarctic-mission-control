"""
Evaluate several destinations and several departure times, and report what
each one measured. Nothing here chooses.

    from src.api.mission_decision import evaluate_mission, DEMONSTRATION_SITES
    matrix = evaluate_mission(sites=DEMONSTRATION_SITES,
                              departure_times=[...])
    matrix.summary()          # which sites and departures routed, and at what
    matrix.select(objective="travel_time_s", direction="min")   # CALLER's rule

WHAT THIS LAYER IS
  A fan-out over the EXISTING orchestration. One scenario is one (site,
  departure time) pair; each is handed to route_profiles.compare_profiles()
  with identical vessel parameters, routing configuration and environmental
  policy, and its answer is recorded verbatim. There is no second A*, no second
  cost model, no second fuel model and no new constraint.

WHAT THIS LAYER REFUSES TO DO
  It does not rank sites, rank departure times, name a best or recommended
  option, or compute an overall score. Those are preferences, and this project
  has none to express. select() exists, but it will not run without a caller
  naming the metric and the direction, and what it returns records that the
  criterion came from the caller.

FEASIBILITY IS THE ROUTER'S WORD, NEVER THIS LAYER'S
  An option is feasible when the existing routing layer returned a route for at
  least one requested profile. It is infeasible only when the router itself
  refused, and the refusal carries the router's OWN outcome and reason. A high
  cost, a high POLARIS penalty, a high iceberg exposure and a high estimated
  fuel are MEASURED ATTRIBUTES, not refusals: nothing here turns a number into
  an infeasibility, and REFUSAL_OUTCOMES is checked against the routing
  module's own vocabulary at import so a new category cannot be invented here.

DEPARTURE TIME IS TWO THINGS AT ONCE
  `departure_time` is the wall clock, which the routing layer checks against
  the environment dates. `departure_offset_s` is how far into the provider's
  own timeline the route starts, which decides the arrival buckets. This module
  derives the second from the first against a stated reference so the two can
  never disagree, and records both.

  A later departure has LESS provider horizon left, not more. On the shipped
  12 h provider a departure at or after 12 h has no bucket left to price at
  all, and the router says so. That is a real limit of the shipped
  configuration, reported as the router words it, not smoothed over.

NOTHING HERE IS AN OPERATIONAL MISSION
  The repository documents one endpoint pair (src/api/config.py DEMO) and no
  station or port coordinates at all. Every other site in DEMONSTRATION_SITES
  is SYNTHETIC, generated by a stated deterministic rule, and carries
  is_operational_mission = False. No synthetic coordinate is described as a
  station, port, base or waypoint.
"""
