@dataclass(frozen=True)
class MissionMatrix:
    """Every alternative that was evaluated. Not a ranking."""

    options: tuple[MissionOption, ...]
    start: tuple[int, int]
    sites: tuple[Site, ...]
    departure_times: tuple[datetime, ...]
    profiles: tuple[str, ...]
    environment_policy: str
    evaluation_mode: str = MODE_OPERATIONAL_DEMO
    is_operational_assessment: bool = True
    iceberg_exposure: str = "priced"
    limitations: tuple[str, ...] = ()

    @property
    def feasible(self) -> tuple[MissionOption, ...]:
        return tuple(o for o in self.options if o.feasible)

    @property
    def any_feasible(self) -> bool:
        return bool(self.feasible)

    def summary(self) -> dict:
        """PHASE 7: the questions a caller may ask, and no verdict."""
        feas = self.feasible
        by_site, by_departure = {}, {}
        for o in self.options:
            by_site.setdefault(o.scenario.site.site_id, []).append(o.feasible)
            by_departure.setdefault(
                o.scenario.departure_time.isoformat(), []).append(o.feasible)
        objectives_available = sorted({
            name for o in feas for name, v in o.objective_values().items()
            if v.get("routed")})
        out = {
            "start": list(self.start),
            "environment_policy": self.environment_policy,
            "evaluation_mode": self.evaluation_mode,
            "is_operational_assessment": self.is_operational_assessment,
            "iceberg_exposure": self.iceberg_exposure,
            "limitations": list(self.limitations),
            "profiles_requested": list(self.profiles),
            "options_evaluated": len(self.options),
            "options_feasible": len(feas),
            "sites_feasible": sorted(k for k, v in by_site.items() if any(v)),
            "sites_infeasible": sorted(k for k, v in by_site.items()
                                       if not any(v)),
            "departures_feasible": sorted(k for k, v in by_departure.items()
                                          if any(v)),
            "departures_infeasible": sorted(k for k, v in by_departure.items()
                                            if not any(v)),
            "objectives_available": objectives_available,
            "options": [
                {"scenario_id": o.scenario.scenario_id,
                 "site": o.scenario.site.site_id,
                 "departure_time": o.scenario.departure_time.isoformat(),
                 "feasible": o.feasible,
                 "refusal_outcome": o.refusal_outcome,
                 "refusal_reason": o.refusal_reason,
                 "environment_source_types":
                     o.environment.get("source_types"),
                 "environment_models": o.environment.get("models"),
                 "buckets_used": o.environment.get("buckets_used"),
                 "objectives": o.objective_values()}
                for o in self.options],
            "route_differences": self._differences(),
            #  the things this layer will not say
            "this_is_not_a_ranking": True,
            "has_a_best_site": False,
            "has_a_best_departure_time": False,
            "has_a_recommended_route": False,
            "has_an_overall_score": False,
            "selection_requires_a_caller_supplied_objective": True,
        }
        if not feas:
            out["outcome"] = NO_FEASIBLE_OPTION
            out["no_feasible_option"] = True
            out["why"] = sorted({
                f"{o.refusal_outcome}: {o.refusal_reason}"
                for o in self.options if o.refusal_outcome})
        else:
            out["outcome"] = "options_evaluated"
            out["no_feasible_option"] = False
        return out

    def _differences(self) -> list:
        """Where the returned geometry differs, per site, across departures.
        A measurement, with no claim about which one is preferable."""
        rows = []
        for site in self.sites:
            paths = {}
            for o in self.options:
                if o.scenario.site.site_id != site.site_id:
                    continue
                p = o.profiles.get(PROFILE_RISK) or {}
                if o.feasible and p.get("success"):
                    paths[o.scenario.departure_time.isoformat()] = \
                        tuple(tuple(c) for c in p["path"])
            if len(paths) < 2:
                continue
            keys = sorted(paths)
            first = paths[keys[0]]
            for k in keys[1:]:
                other = paths[k]
                shared = len(set(first) & set(other))
                diverge = next((i for i, (a, b) in enumerate(zip(first, other))
                                if a != b), None)
                rows.append({
                    "site": site.site_id, "profile": PROFILE_RISK,
                    "departure_a": keys[0], "departure_b": k,
                    "path_changed": first != other,
                    "shared_cells": shared,
                    "first_divergence_index": diverge})
        return rows

    def select(self, *, objective: str, direction: str,
               among: str = "feasible") -> dict:
        """Pick one option BY A CRITERION THE CALLER SUPPLIED.

        There is no default objective and no default direction, because a
        default would be this layer expressing a preference. The answer records
        whose criterion it was.
        """
        if objective not in NOT_FEASIBILITY_CRITERIA + (
                "distance_km", "travel_time_h", "estimated_fuel_per_km"):
            raise MissionError(
                f"{objective!r} is not a measured attribute of an option; "
                f"choose one of {sorted(set(NOT_FEASIBILITY_CRITERIA) | {'distance_km', 'travel_time_h', 'estimated_fuel_per_km'})}")
        if direction not in ("min", "max"):
            raise MissionError(
                f"direction must be 'min' or 'max', got {direction!r}; this "
                f"layer has no opinion about which way is better")
        if among != "feasible":
            raise MissionError("only feasible options can be selected among")
        rows = []
        for o in self.feasible:
            for name, v in o.objective_values().items():
                if v.get("routed") and v.get(objective) is not None:
                    rows.append((float(v[objective]), o, name))
        if not rows:
            return {"selected": None,
                    "why": f"no feasible option reports {objective}",
                    "criterion_supplied_by": "caller"}
        best = (min if direction == "min" else max)(rows, key=lambda r: r[0])
        value, option, profile = best
        ties = [r for r in rows if r[0] == value]
        return {
            "selected": {"scenario_id": option.scenario.scenario_id,
                         "site": option.scenario.site.site_id,
                         "departure_time":
                             option.scenario.departure_time.isoformat(),
                         "profile": profile, "value": value},
            "objective": objective, "direction": direction,
            "ties": len(ties),
            "criterion_supplied_by": "caller",
            "this_is_not_a_recommendation": True,
            "what_this_means": (
                f"among the feasible options, this one has the {direction}imum "
                f"{objective}. That is arithmetic on the caller's criterion, "
                f"not a judgement by this system that it is the option to "
                f"take."),
        }

    def to_dict(self) -> dict:
        return {"start": list(self.start),
                "sites": [s.to_dict() for s in self.sites],
                "departure_times": [d.isoformat() for d in self.departure_times],
                "profiles_requested": list(self.profiles),
                "environment_policy": self.environment_policy,
                "evaluation_mode": self.evaluation_mode,
                "is_operational_assessment": self.is_operational_assessment,
                "iceberg_exposure": self.iceberg_exposure,
                "limitations": list(self.limitations),
                "options": [o.to_dict() for o in self.options],
                "summary": self.summary()}


# ------------------------------------------------------------- evaluation
def _res(bucket: dict, key: str):
    """Read a field either from the bucket record or from the resolver's own
    answer nested under it. One lookup, two shapes, no filename parsing."""
    if bucket.get(key) is not None:
        return bucket[key]
    return (bucket.get("resolution") or {}).get(key)


def _with_lineage(bucket: dict, *, forecast_dir=None) -> dict:
    """Add the artifact lineage to one forecast-priced bucket.

    The resolution is by SHA match, exactly as the long-horizon harness does
    it: the raster names its model artifact and that artifact's SHA, and the
    training metrics file whose recorded artifact SHA equals it names the
    dataset. Never by filename, lead number or ordering.
    """
    out = dict(bucket)
    if out.get("source_type") != SOURCE_FORECAST:
        return out
    name = (out.get("resolution") or {}).get("path")
    if not name:
        return out
    out.update(_artifact_lineage(Path(forecast_dir or FORECAST_DIR) / name))
    return out


def _environment_for(world, option_profiles: dict, *, timeline=None,
                     field_provenance=None, forecast_dir=None) -> dict:
    """The environmental provenance for the buckets THIS option actually used.

    Under the forecast policy the summary comes from the option's OWN timeline,
    never from the world's persistence summary, and every forecast-priced
    bucket is enriched with the artifact lineage the harness already resolves
    by SHA match.
    """
    summary = (dict(timeline_summary(timeline)) if timeline is not None
               else dict(world["environment_summary"]))
    used = set()
    for p in option_profiles.values():
        if p.get("success"):
            used.update(int(b) for b in (p.get("buckets_used") or ()))
    if field_provenance is not None:
        #  the fields' own records, which carry the resolver's full answer
        buckets = [_with_lineage(dict(field_provenance[b], bucket=b),
                                 forecast_dir=forecast_dir)
                   for b in sorted(used) if b in field_provenance]
    else:
        buckets = [b for b in summary.get("buckets", [])
                   if int(b.get("bucket", -1)) in used]
    return {
        "policy": summary.get("policy"),
        "analysis_date": summary.get("analysis_date"),
        "environment_dates": summary.get("environment_dates"),
        "environment_is_time_varying": summary.get(
            "environment_is_time_varying"),
        "source_types": sorted({b.get("source_type") for b in buckets}) or None,
        "models": sorted({b["model"] for b in buckets if b.get("model")}) or [],
        "forecast_origins": sorted({_res(b, "forecast_origin") for b in buckets
                                    if _res(b, "forecast_origin")}) or [],
        "forecast_leads": sorted({_res(b, "lead_hours") for b in buckets
                                  if _res(b, "lead_hours") is not None}) or [],
        "validity_rules": sorted({_res(b, "validity_rule") for b in buckets
                                  if _res(b, "validity_rule")}) or [],
        "artifacts": sorted({_res(b, "path") for b in buckets
                             if _res(b, "path")}) or [],
        "buckets_used": sorted(used),
        "buckets": buckets,
    }


def _long_horizon_environment(policy: str, *, departure: datetime, buckets: int,
                              world, bucket_hours: float,
                              forecast_dir: Path | None = None):
    """Build the evaluation provider for one departure, from scratch.

    This is the whole integration seam. The evaluation harness and the mission
    layer already converge on route_profiles.compare_profiles(); all that was
    missing was a provider built from the forecast-aware fields instead of the
    world's persistence provider, and the per-bucket sea ice that goes with it.

    Returns (provider, sic_for_bucket, timeline, sources). The provider carries
    NO iceberg layer: see ICEBERG_OMISSION_REASON, which is imported from the
    harness rather than restated here.
    """
    if policy not in SUPPORTED_POLICIES:
        raise MissionError(f"{policy!r} is not a supported policy")
    forecast = policy in FORECAST_POLICIES
    bucket_list = list(range(int(buckets)))
    kw = {} if forecast_dir is None else {"forecast_dir": Path(forecast_dir)}
    common = dict(buckets=bucket_list, bucket_seconds=bucket_hours * HOUR,
                  departure_time=departure, analysis_date=world["day"],
                  available_dates=environment_dates())

    def resolver():
        """None for persistence: the baseline resolves no forecast at all.
        This is the same construction src/api/long_horizon_evaluation.py uses
        for its own two runs, so the baseline here IS that baseline."""
        if not forecast:
            return None
        return resolver_for_policy(policy, origin_time=departure, **kw)

    timeline = (plan_environment_timeline(policy=policy, **common) if not forecast
                else plan_environment_timeline(
                    policy=policy, on_missing=ON_MISSING_PERSIST,
                    resolver=resolver(), **common))
    fields = forecast_aware_fields(
        timeline=timeline,
        resolver=resolver(),
        grid=world["grid"], constraints=world["constraints"],
        polaris_penalties=world["polaris"].penalties,
        comp_config=load_composition_config(COMP_CONFIG), usnic_dir=USNIC,
        chart_date=world["chart_date"], analysis_date=world["day"],
        bucket_hours=bucket_hours, sic_for_date=lambda day: world["grid"])
    #  The per-bucket sea ice the fuel proxy needs. resolve_bucket_sources is
    #  the SAME call forecast_aware_fields makes internally, so the two must
    #  name the same artifact for every bucket -- checked, not assumed.
    sources = resolve_bucket_sources(
        timeline, resolver=resolver(),
        grid=world["grid"], sic_for_date=lambda day: world["grid"])
    by_field = {f.bucket: (f.environment.get("resolution") or {}).get("path")
                for f in fields}
    #  Keep ONE array per distinct source, not one per bucket. Sixteen buckets
    #  over three sources would otherwise hold sixteen full 1328x1264 grids --
    #  about 215 MB of identical data, which is enough to end the process.
    sic_by_key: dict = {}
    bucket_key: dict = {}
    for src in sources:
        want = src.resolution.path.name if src.resolution else None
        if by_field.get(src.bucket) != want:
            raise MissionError(
                f"bucket {src.bucket} was priced from {by_field.get(src.bucket)!r} "
                f"but its sea-ice field was read from {want!r}; the fuel proxy "
                f"and the routing cost must read the same artifact")
        key = (src.origin, want or src.entry.environment_date.isoformat())
        sic_by_key.setdefault(key, src.sic)
        bucket_key[int(src.bucket)] = key
    source_count = len(sic_by_key)
    del sources

    #  NO iceberg layer, deliberately: the configured exposure horizon is 12 h
    provider = TimeIndexedNavigationCost.from_fields(
        fields, bucket_seconds=bucket_hours * HOUR,
        allow_historical_demo_mismatch=True)

    def sic_for(bucket: int):
        try:
            return sic_by_key[bucket_key[int(bucket)]]
        except KeyError:
            raise MissionError(
                f"no sea-ice field was resolved for bucket {bucket}; the fuel "
                f"proxy will not fall back to another bucket's ice") from None

    #  The FIELDS carry the resolver's full answer per bucket (resolution:
    #  path, lead, validity rule and window). The timeline summary does not, so
    #  the per-bucket provenance is taken from the fields -- the same records
    #  the long-horizon harness reports -- never parsed out of a filename.
    field_provenance = {int(f.bucket): dict(f.environment or {}) for f in fields}
    return provider, sic_for, timeline, field_provenance


def evaluate_scenario(scenario: MissionScenario, *, world=None,
                      risk_provider=None, grid_factory=None) -> MissionOption:
    """Route ONE scenario through the existing orchestration, from scratch.

    Nothing is carried over from another scenario: a fresh grid, a fresh
    constraint layer and a fresh comparison every time, with this scenario's
    own departure offset deciding its own arrival buckets.
    """
    world = world or get_world()
    #  A world for another DATE brings its own grid factory: fresh_grid() is
    #  bound to the shipped demo day, so an evaluation over a different day
    #  must supply its own or it would route on the wrong grid.
    grid_factory = grid_factory or fresh_grid
    forecast_timeline = None
    field_provenance = None
    if scenario.evaluation_mode == MODE_LONG_HORIZON_EVALUATION:
        #  the OPT-IN path: a provider built from the forecast-aware fields,
        #  with no iceberg layer. Nothing here can be reached without the
        #  caller having named this policy.
        try:
            provider, sic_source, forecast_timeline, field_provenance = \
                _long_horizon_environment(
                    scenario.environment_policy,
                    departure=scenario.departure_time,
                    buckets=int(scenario.horizon_buckets or 0),
                    world=world, bucket_hours=float(DEMO["bucket_hours"]),
                    forecast_dir=(Path(scenario.forecast_dir)
                                  if scenario.forecast_dir else None))
        except (EnvironmentProviderError, ValueError) as exc:
            if isinstance(exc, MissionError):
                raise
            return MissionOption(
                scenario=scenario, feasible=False,
                refusal_outcome=OUTCOME_FORECAST_UNAVAILABLE,
                refusal_reason=str(exc))
    else:
        provider = risk_provider or world["provider"]
        sic_source = sic_for_bucket()
    try:
        comparison = compare_profiles(
            grid_factory, risk_provider=provider, usnic_dir=USNIC,
            start=tuple(scenario.start), goal=tuple(scenario.site.cell),
            departure_time=scenario.departure_time,
            vessel_speed_mps=scenario.vessel_speed_mps,
            constraints_factory=lambda g: NavigationDomain(g).add_geotiff(
                "land_mask", BEDMACHINE),
            polaris_ice_class=scenario.polaris_ice_class,
            polaris_riv_table=scenario.polaris_riv_table,
            polaris_penalties=world["polaris"],
            sic_for_bucket=sic_source,
            allow_historical_demo_override=True,
            departure_offset_s=float(scenario.departure_offset_s))
    except ProfileError as exc:
        return MissionOption(
            scenario=scenario, feasible=False,
            refusal_outcome=OUTCOME_HARD_CONSTRAINT, refusal_reason=str(exc))

    payload = comparison.to_dict()["profiles"]
    wanted = {n: payload[n] for n in scenario.profiles if n in payload}
    routed = {n: p for n, p in wanted.items() if p.get("success")}
    env = _environment_for(world, routed, timeline=forecast_timeline,
                           field_provenance=field_provenance,
                           forecast_dir=(Path(scenario.forecast_dir)
                                         if scenario.forecast_dir else None))

    if routed:
        return MissionOption(scenario=scenario, feasible=True,
                             refusal_outcome=None, refusal_reason=None,
                             profiles=wanted, environment=env)

    #  every requested profile was refused. The outcome is the ROUTER's, taken
    #  from the profile that was asked for first, and it must be one the
    #  routing module defines -- never a threshold invented here.
    first = wanted[next(iter(wanted))] if wanted else {}
    outcome = first.get("outcome")
    if outcome not in REFUSAL_OUTCOMES:
        raise MissionError(
            f"the routing layer refused with {outcome!r}, which is not one of "
            f"its own refusal outcomes {REFUSAL_OUTCOMES}. This layer will not "
            f"classify an unknown outcome as an infeasibility.")
    return MissionOption(scenario=scenario, feasible=False,
                         refusal_outcome=outcome,
                         refusal_reason=first.get("reason"),
                         profiles=wanted, environment=env)


def evaluate_mission(*, sites, departure_times, start=None,
                     reference_departure: datetime | None = None,
                     vessel_speed_mps: float | None = None,
                     polaris_ice_class: str | None = None,
                     polaris_riv_table: str | None = None,
                     profiles: tuple[str, ...] = ALL_PROFILES,
                     environment_policy: str | None = None,
                     horizon_buckets: int | None = None,
                     grid_factory=None, forecast_dir=None,
                     world=None) -> MissionMatrix:
    """Evaluate every (site, departure time) pair independently.

    environment_policy defaults to persistence -- the demo's policy, unchanged.
    The forecast policy is reached only by naming it.
    """
    world = world or get_world()
    start = tuple(start or DEMO["start"])
    reference = reference_departure or datetime.fromisoformat(
        DEMO["departure_time"])
    speed = float(DEMO["vessel_speed_mps"] if vessel_speed_mps is None
                  else vessel_speed_mps)
    ice_class = polaris_ice_class or DEMO["polaris_ice_class"]
    riv = polaris_riv_table or DEMO["polaris_riv_table"]
    sites = tuple(sites)
    departure_times = tuple(departure_times)
    if not sites:
        raise MissionError("at least one candidate destination is required")
    if not departure_times:
        raise MissionError("at least one departure time is required")
    unknown = [p for p in profiles if p not in ALL_PROFILES]
    if unknown:
        raise MissionError(f"unknown profiles {unknown}; have {ALL_PROFILES}")

    policy = environment_policy or DEFAULT_POLICY
    if policy not in SUPPORTED_POLICIES:
        raise MissionError(
            f"{policy!r} is not a policy this layer routes under; it supports "
            f"{list(SUPPORTED_POLICIES)}. The requested policy is refused "
            f"rather than replaced with a supported one.")
    forecast = policy in FORECAST_POLICIES
    #  EVALUATION MODE is entered by asking for a forecast policy, or by asking
    #  for a horizon longer than the world's own provider. Either way it is the
    #  caller's explicit request: the default path -- no policy, no horizon --
    #  is the shipped demo configuration, untouched.
    evaluation = forecast or horizon_buckets is not None
    if not evaluation:
        #  the default path must still be the policy the world actually
        #  resolved, so persistence cannot silently mean something else
        resolved = world["environment_summary"].get("policy")
        if resolved != policy:
            raise MissionError(
                f"this backend resolved the environment under {resolved!r}, "
                f"but the mission asked for {policy!r}")
    planned = (int(horizon_buckets or LONG_HORIZON_SCENARIO["buckets"])
               if evaluation else None)
    if planned is not None and planned < 1:
        raise MissionError(f"horizon_buckets must be >= 1, got {planned}")
    mode = (MODE_LONG_HORIZON_EVALUATION if evaluation
            else MODE_OPERATIONAL_DEMO)
    options = []
    for site in sites:
        for departure in departure_times:
            offset = (departure - reference).total_seconds()
            if offset < 0:
                raise MissionError(
                    f"departure {departure.isoformat()} is before the "
                    f"reference {reference.isoformat()}; the provider's "
                    f"timeline does not extend backwards")
            scenario = MissionScenario(
                scenario_id=f"{site.site_id}@{departure.isoformat()}",
                start=start, site=site, departure_time=departure,
                departure_offset_s=offset, vessel_speed_mps=speed,
                polaris_ice_class=ice_class, polaris_riv_table=riv,
                profiles=tuple(profiles), environment_policy=policy,
                evaluation_mode=mode,
                #  PHASE 3: an evaluation run omits the iceberg term, so it is
                #  NOT an operational assessment and never claims to be
                is_operational_assessment=not evaluation,
                iceberg_exposure=(ICEBERG_OMITTED if evaluation else "priced"),
                iceberg_omission_reason=(ICEBERG_OMISSION_REASON if evaluation
                                         else None),
                horizon_buckets=planned,
                forecast_dir=(str(forecast_dir) if forecast_dir else None),
                #  DERIVED, never asserted: a mission is operational only if
                #  its destination is a real operational location, and no
                #  coordinate in this repository is one. Computing it here
                #  means a synthetic site can never be labelled operational by
                #  someone editing a default.
                is_operational_mission=bool(site.is_operational))
            options.append(evaluate_scenario(
                scenario, world=world, grid_factory=grid_factory,
                risk_provider=world.get("provider")))
    return MissionMatrix(
        options=tuple(options), start=start, sites=sites,
        departure_times=departure_times, profiles=tuple(profiles),
        environment_policy=policy, evaluation_mode=mode,
        is_operational_assessment=not evaluation,
        iceberg_exposure=(ICEBERG_OMITTED if evaluation else "priced"),
        limitations=(EVALUATION_LIMITATIONS if evaluation else ()))


def main() -> int:
    """The demonstration matrix: three sites x four departure times."""
    import json
    base = datetime.fromisoformat(DEMO["departure_time"])
    departures = [base + timedelta(hours=h) for h in (0, 6, 12, 18)]
    m = evaluate_mission(sites=DEMONSTRATION_SITES, departure_times=departures)
    s = m.summary()
    print("=" * 78)
    print("MISSION DECISION MATRIX -- no site, departure or route is ranked")
    print("=" * 78)
    print(f"  start {m.start}  policy {m.environment_policy}")
    print(f"  {s['options_feasible']} of {s['options_evaluated']} options "
          f"routed; outcome {s['outcome']}")
    print()
    for o in m.options:
        sc = o.scenario
        head = f"  {sc.site.site_id:<11} {sc.departure_time.strftime('%d %H:%M')}"
        if not o.feasible:
            print(f"{head}  INFEASIBLE  {o.refusal_outcome}")
            print(f"{'':<26}{(o.refusal_reason or '')[:78]}")
            continue
        print(f"{head}  feasible")
        for name, v in o.objective_values().items():
            if not v["routed"]:
                print(f"{'':<26}{name:<18} refused: {v['outcome']}")
                continue
            print(f"{'':<26}{name:<18} {v['distance_km']:8.3f} km "
                  f"{v['travel_time_h']:7.3f} h  cost {v['configured_cost']:,.1f}"
                  f"  fuel {v['estimated_fuel']:,.0f} OWE-m")
    print()
    print(json.dumps({k: v for k, v in s.items()
                      if k not in ("options", "route_differences")}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
